"""Objective checks for exact source quotes; business meaning remains model-owned."""

import re
from decimal import Decimal
from typing import Literal

from app.domain.brokerage import parse_broker_decimal

# Numeric/currency syntax is closed. There are deliberately no business-language keyword lists.
NUMBER_TOKEN = re.compile(r"(?<![\w\d])\d+(?:[.,]\d+)*(?!\d)")
DOLLAR_PREFIX = re.compile(r"(?:\$|USD|USDT)\s*$", re.I)
DOLLAR_SUFFIX = re.compile(r"^\s*(?:\$|USD\b|USDT\b)", re.I)
BOLIVAR_PREFIX = re.compile(r"(?:\bBs\.?|\bVES)\s*$", re.I)
BOLIVAR_SUFFIX = re.compile(r"^\s*(?:Bs\b|VES\b)", re.I)


def _has_currency_prefix(message: str, number_start: int, pattern: re.Pattern) -> bool:
    prefix = pattern.search(message[:number_start])
    if prefix is None:
        return False
    # In "100$ 80000" the dollar sign is the first number's suffix.
    # A currency marker attached to the preceding number must not label the
    # next number too. This checks token adjacency, never the business meaning.
    before_marker = message[:prefix.start()]
    if before_marker and before_marker[-1].isdigit():
        return False
    if prefix.group()[-1].isspace() and before_marker.rstrip()[-1:].isdigit():
        return False
    return True


def validate_quoted_money_source(
    message: str,
    source_quote: str | None,
    expected_value: Decimal,
    *,
    expected_currency: Literal["USD", "VES"] = "VES",
) -> dict | None:
    """Verify one exact, unique quote containing one complete numeric token.

    This does not infer whether a number means Bs, rate, balance or reference. The model declares
    the field and quote. We only verify presence, numeric identity and explicit currency syntax.
    Global token boundaries prevent citing '800' inside '80000'. Ambiguous/repeated quotes require
    a more specific fragment. Offsets are generated by the server, never trusted model offsets.
    """
    if not source_quote:
        return None
    message_tokens = list(NUMBER_TOKEN.finditer(message))
    quoted_tokens = []
    quote_start = message.find(source_quote)
    while quote_start >= 0:
        quote_end = quote_start + len(source_quote)
        tokens = [token for token in message_tokens
                  if quote_start <= token.start() and token.end() <= quote_end]
        if len(tokens) == 1:
            quoted_tokens.append(tokens[0])
        quote_start = message.find(source_quote, quote_start + 1)
    # "900" inside "990000" is not another complete numeric occurrence.
    # Two actual occurrences still require a more specific literal quote.
    if len(quoted_tokens) != 1:
        return None
    token = quoted_tokens[0]
    try:
        if parse_broker_decimal(token.group()) != expected_value:
            return None
    except ValueError:
        return None
    after_number = message[token.end() :]
    explicitly_usd = bool(_has_currency_prefix(message, token.start(), DOLLAR_PREFIX)
                          or DOLLAR_SUFFIX.match(after_number))
    explicitly_bolivars = bool(_has_currency_prefix(message, token.start(), BOLIVAR_PREFIX)
                               or BOLIVAR_SUFFIX.match(after_number))
    if expected_currency == "VES" and explicitly_usd or expected_currency == "USD" and explicitly_bolivars:
        return None
    return {
        "value": str(expected_value),
        "quote": source_quote,
        "start": token.start(),
        "end": token.end(),
        "validation": "exact_quote",
    }


def source_spans_overlap(first: dict, second: dict) -> bool:
    """A single numeric occurrence cannot supply two independently entered monetary fields."""
    return first["start"] < second["end"] and second["start"] < first["end"]
